/** Iran has no DST, so the local day boundary is a fixed UTC+3:30. */
export function iranDateString(now: Date = new Date()): string {
  return new Date(now.getTime() + 3.5 * 3600 * 1000).toISOString().slice(0, 10);
}

/** Deterministic: same date + same conversation always gives the same question. */
export function todaysQuestion(conversationId: string, dateIso: string): string {
  const dayNumber = Math.floor(Date.parse(dateIso + 'T00:00:00Z') / 86_400_000);
  let hash = 0;
  for (const ch of conversationId) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return QUESTIONS[(dayNumber + hash) % QUESTIONS.length];
}
